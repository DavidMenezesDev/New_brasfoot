#!/usr/bin/env python3
"""Extract the fixed fixture tables from `re/decompiled/best/t.java` into C#.

`best.t` holds several hard-coded round-robin schedules (used by `f.s` for
3/4/5/6/9/11/19/25-team competitions).  Transcribing them by hand is
error-prone, so this script parses the Java `int[][][]` literals and emits a
generated C# source file.  Run it after any change to the decompiled source:

    python3 re/tools/extract_fixture_tables.py

It only reads `int[][][]`/`int[][]` fields whose initialiser is a *single
brace literal*, which is true for cX, cY, cZ, da, db, dd, dg and dh.  The small
tables built imperatively in the static block (Jd, dc, Je, de, Jf, df) are
transcribed by hand in FixtureTables.cs.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "re" / "decompiled" / "best" / "t.java"
OUT = ROOT / "dotnet" / "src" / "Brasfoot.Core" / "Competitions" / "FixtureTables.g.cs"

# Fields whose initialiser is a literal, with a short description.
TARGETS = {
    "cX": ("19 times (Série A/C etc.), 19 rodadas x 9 jogos, base 1"),
    "dd": ("9 times, 9 rodadas x 4 jogos, base 1"),
    "dg": ("11 times, 11 rodadas x 5 jogos, base 0"),
    "dh": ("25 times, 25 rodadas x 12 jogos, base 0"),
    "cY": ("fase de grupos (4 grupos de 4), 12 rodadas x 8 jogos, base 1"),
    "cZ": ("fase de grupos (5 grupos de 5?), 15 rodadas x 10 jogos, base 1"),
    "da": ("6 times, 6 rodadas x 3 jogos (cruzamento de grupos), base 1"),
    "db": ("8 times, 8 rodadas x 4 jogos (cruzamento de grupos), base 1"),
}


def find_literal(text: str, name: str) -> str | None:
    m = re.search(rf"\b{name}\s*=\s*new int((?:\[\])*)\s*\{{", text)
    if not m:
        return None
    start = m.end() - 1  # at '{'
    depth = 0
    i = start
    while i < len(text):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[start : i + 1]
        i += 1
    raise ValueError(f"unbalanced braces for {name}")


def parse_literal(lit: str):
    """Parse a Java nested brace literal, stripping inner `new int[]...` casts."""
    lit = re.sub(r"new\s+int\s*(?:\[\s*\])*", "", lit)
    tokens = re.split(r"([{}])", lit)
    stack: list[list] = []
    cur: list = []
    for tok in tokens:
        tok = tok.strip()
        if tok == "":
            continue
        if tok == "{":
            stack.append(cur)
            cur = []
        elif tok == "}":
            parent = stack.pop()
            parent.append(cur)
            cur = parent
        else:
            for part in tok.split(","):
                part = part.strip()
                if part:
                    cur.append(int(part))
    return cur[0]


def depth_of(x) -> int:
    d = 0
    while isinstance(x, list) and x and isinstance(x[0], list):
        x = x[0]
        d += 1
    return d


def to_cs(x, dims: int) -> str:
    """Render a nested list as a C# array literal with `dims` dimensions."""
    if dims == 1:
        return "new int[] { " + ", ".join(str(v) for v in x) + " }"
    tag = "new int" + "[]" * dims
    inner = ",\n            ".join(to_cs(v, dims - 1) for v in x)
    return tag + " {\n            " + inner + "\n        }"


def main() -> int:
    text = SRC.read_text()
    blocks = []
    for name, desc in TARGETS.items():
        lit = find_literal(text, name)
        if lit is None:
            print(f"!! {name} not found (literal)", file=sys.stderr)
            continue
        data = parse_literal(lit)
        dims = depth_of(data) + 1
        blocks.append((name, desc, data, dims))

    lines = [
        "// <auto-generated>",
        "//     Generated by re/tools/extract_fixture_tables.py from re/decompiled/best/t.java.",
        "//     Do not edit manually; re-run the script after re-decompiling.",
        "// </auto-generated>",
        "namespace Brasfoot.Core.Competitions;",
        "",
        "/// <summary>",
        "/// Tabelas fixas de rodízio transcritas de <c>best.t</c> (<c>cX</c>, <c>dd</c>, <c>dg</c>,",
        "/// <c>dh</c>, <c>cY</c>, <c>cZ</c>, <c>da</c>, <c>db</c>). Índices conforme o original",
        "/// (atenção à base 1 de <c>cX</c>/<c>cY</c>/<c>cZ</c>/<c>dd</c>/<c>da</c>/<c>db</c>).",
        "/// </summary>",
        "internal static partial class FixtureTables",
        "{",
    ]
    for name, desc, data, dims in blocks:
        cs = to_cs(data, dims)
        lines.append(f"    /// <summary>{desc}.</summary>")
        lines.append(f"    public static readonly int[][][] {name} = {cs};")
        lines.append("")
    lines.append("}")
    lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(blocks)} tables)")
    for name, desc, data, dims in blocks:
        print(f"  {name}: {dims} dims, {len(data)} top-level entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
