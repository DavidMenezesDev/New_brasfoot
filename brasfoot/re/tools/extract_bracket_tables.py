#!/usr/bin/env python3
"""Extrai as matrizes de chaveamento do mata-mata de `re/decompiled/f/s.java`.

As matrizes `Zm..Zz` (f/s.java:65-78) são `int[]` literais inicializadas no construtor
sem argumentos `public s()`. Elas são permutações: a lista de classificados `arrayList`
vira a chave `arrayList2[i] = arrayList[matrix[i]]` (f/s.java:837, 911, 951), e depois
`f.G` emparelha `(0,1),(2,3),...` (f/G.java:64-76).

Gera `dotnet/src/Brasfoot.Core/Competitions/BracketTables.g.cs`.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "re" / "decompiled" / "f" / "s.java"
DEST = ROOT / "dotnet" / "src" / "Brasfoot.Core" / "Competitions" / "BracketTables.g.cs"

NAMES = ["Zm", "Zn", "Zo", "Zp", "Zq", "Zr", "Zs", "Zt", "Zu", "Zv", "Zw", "Zx", "Zy", "Zz"]


def extract_method_body(text: str, start_index: int) -> str:
    """Corpo da primeira chave `{...}` a partir de `start_index` (balanceada)."""
    i = text.index("{", start_index)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i + 1 : j]
    raise ValueError("chave não balanceada")


def parse_constructor(body: str) -> dict[str, list[int]]:
    declarations: dict[str, int] = {}
    values: dict[str, dict[int, int]] = {}
    aliases: dict[str, str] = {}
    arrays: dict[str, list[int]] = {}

    for line in body.splitlines():
        line = line.strip()
        m = re.match(r"int\[\]\s+(\w+)\s*=\s*new\s+int\[(\d+)\];", line)
        if m:
            declarations[m.group(1)] = int(m.group(2))
            values[m.group(1)] = {}
            continue
        m = re.match(r"(\w+)\[(\d+)\]\s*=\s*(\d+);", line)
        if m:
            values[m.group(1)][int(m.group(2))] = int(m.group(3))
            continue
        m = re.match(r"int\[\]\s+(\w+)\s*=\s*(\w+);", line)
        if m:
            aliases[m.group(1)] = m.group(2)
            continue
        m = re.match(r"this\.(\w+)\s*=\s*(\w+);", line)
        if m:
            name, var = m.group(1), m.group(2)
            if name not in NAMES:
                continue
            if var in declarations:
                size = declarations[var]
                arr = [0] * size
                for idx, val in values.get(var, {}).items():
                    arr[idx] = val
                arrays[name] = arr
            elif var in aliases:
                arrays[name] = arrays[aliases[var]]
            elif var in arrays:
                arrays[name] = arrays[var]
            else:
                raise ValueError(f"matriz {name} aponta para variável desconhecida {var}")
    return arrays


def main() -> int:
    text = SOURCE.read_text(encoding="utf-8")

    ctor0 = text.index("public s() {")
    arrays0 = parse_constructor(extract_method_body(text, ctor0))

    # O construtor principal reinicializa as mesmas matrizes: confere que batem.
    ctor1 = text.index("public s(LoadLigaOptions", ctor0)
    arrays1 = parse_constructor(extract_method_body(text, ctor1))

    missing = [n for n in NAMES if n not in arrays0]
    if missing:
        print(f"matrizes ausentes: {missing}", file=sys.stderr)
        return 1
    for name in NAMES:
        a, b = arrays0[name], arrays1.get(name)
        if b is not None and a != b:
            print(f"divergência entre construtores em {name}: {a} != {b}", file=sys.stderr)
            return 1
        if sorted(a) != list(range(len(a))):
            print(f"aviso: {name} não é permutação de 0..{len(a) - 1}: {a}", file=sys.stderr)

    lines = [
        "// <auto-generated>",
        "// Gerado por re/tools/extract_bracket_tables.py a partir de re/decompiled/f/s.java.",
        "// Não editar à mão: rode o script de novo.",
        "// </auto-generated>",
        "",
        "namespace Brasfoot.Core.Competitions;",
        "",
        "/// <summary>Matrizes de chaveamento do mata-mata (<c>f.s.Zm..Zz</c>, <c>f/s.java:74-243</c>).</summary>",
        "public static partial class BracketTables",
        "{",
    ]
    for name in NAMES:
        arr = arrays0[name]
        lines.append(f"    /// <summary><c>f.s.{name}</c> ({len(arr)} times).</summary>")
        lines.append(f"    public static readonly int[] {name} = [{', '.join(str(v) for v in arr)}];")
        lines.append("")
    # remove a última linha em branco antes do fecha-chaves
    if lines[-1] == "":
        lines.pop()
    lines.append("}")
    lines.append("")

    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text("\n".join(lines), encoding="utf-8")
    print(f"escrito {DEST.relative_to(ROOT)} ({len(NAMES)} matrizes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
